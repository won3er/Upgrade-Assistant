import type { AnalysisResult, Finding, MigrationResult, UpgradePlan } from '../domain/types.js';

/**
 * Renders the Migration Report — the artifact users share with their team.
 * Structure follows the product spec: Summary, Libraries, Breaking
 * Changes, Affected Files, Risk, Estimated Time, Checklist, Official Links.
 */
export class ReportGenerator {
  toMarkdown(analysis: AnalysisResult, migration?: MigrationResult): string {
    const lines: string[] = [];
    const total = analysis.plans.length;
    const totalMinutes = analysis.plans.reduce((s, p) => s + p.estimatedMinutes, 0);

    lines.push('# Migration Report');
    lines.push('');
    lines.push(`> Generated by [Upgrade Assistant](https://github.com/won3er/Upgrade-Assistant) on ${analysis.createdAt.slice(0, 10)} for **${analysis.projectName}**.`);
    lines.push('');

    lines.push('## Summary');
    lines.push('');
    if (total === 0) {
      lines.push('Everything supported by the installed plugins is up to date. 🎉');
    } else {
      lines.push(
        `${total} upgrade${total > 1 ? 's' : ''} available · ` +
          `${countFindings(analysis)} breaking-change findings in ${countAffectedFiles(analysis)} files · ` +
          `estimated effort **${formatMinutes(totalMinutes)}**.`,
      );
    }
    lines.push('');

    if (total > 0) {
      lines.push('## Libraries');
      lines.push('');
      lines.push('| Library | Current | Target | Jump | Risk | Estimate |');
      lines.push('|---|---|---|---|---|---|');
      for (const plan of analysis.plans) {
        const c = plan.candidate;
        lines.push(
          `| ${c.packageName} | ${c.currentVersion} | ${c.targetVersion} | ${c.diff ?? '—'} | ${riskBadge(plan)} | ${formatMinutes(plan.estimatedMinutes)} |`,
        );
      }
      lines.push('');
    }

    for (const plan of analysis.plans) {
      lines.push(...this.renderPlan(plan));
    }

    if (migration) {
      lines.push(...this.renderMigration(migration));
    }

    lines.push(...this.renderChecklist(analysis));
    lines.push(...this.renderSources(analysis));

    if (analysis.warnings.length > 0) {
      lines.push('## Analysis warnings');
      lines.push('');
      for (const warning of analysis.warnings) lines.push(`- ${warning}`);
      lines.push('');
    }

    return lines.join('\n');
  }

  private renderPlan(plan: UpgradePlan): string[] {
    const c = plan.candidate;
    const lines: string[] = [];
    lines.push(`## ${c.packageName} ${c.currentVersion} → ${c.targetVersion}`);
    lines.push('');
    lines.push(`Risk: ${riskBadge(plan)} · Estimated effort: **${formatMinutes(plan.estimatedMinutes)}**`);
    lines.push('');

    if (plan.findings.length === 0) {
      lines.push('No usages affected by known breaking changes were found in this project.');
      lines.push('');
      return lines;
    }

    lines.push('### Breaking changes affecting this project');
    lines.push('');
    for (const finding of plan.findings) {
      lines.push(`#### ${severityIcon(finding)} ${finding.rule.title} (\`${finding.rule.id}\`)`);
      lines.push('');
      lines.push(finding.rule.description);
      lines.push('');
      lines.push(`Fix: ${fixLabel(finding)}${finding.rule.officialCodemod ? ` — \`${finding.rule.officialCodemod}\`` : ''}`);
      lines.push('');
      lines.push('Affected files:');
      lines.push('');
      for (const match of finding.matches.slice(0, 30)) {
        const note = match.note ? ` — ${match.note}` : '';
        lines.push(`- \`${match.filePath}:${match.line}\`${note}`);
      }
      if (finding.matches.length > 30) {
        lines.push(`- …and ${finding.matches.length - 30} more`);
      }
      lines.push('');
    }

    lines.push('### Plan');
    lines.push('');
    for (const step of plan.steps) {
      lines.push(`${step.order}. **${step.title}** — ${step.detail} _(≈${formatMinutes(step.estimatedMinutes)})_`);
    }
    lines.push('');
    return lines;
  }

  private renderMigration(migration: MigrationResult): string[] {
    const lines: string[] = [];
    lines.push(`## Migration ${migration.dryRun ? '(dry run) ' : ''}result`);
    lines.push('');
    lines.push(`- ${migration.modifiedFiles.length} files modified`);
    lines.push(`- ${migration.appliedFixes.reduce((s, f) => s + f.fixesApplied, 0)} automatic fixes applied`);
    for (const dep of migration.dependencyUpdates) {
      lines.push(`- ${dep.packageName}: \`${dep.from}\` → \`${dep.to}\``);
    }
    if (migration.verification?.ran) {
      const v = migration.verification;
      lines.push(
        `- Verification: ${v.typecheckPassed ? '✅ typecheck passed' : `❌ typecheck failed (${v.errorCount} errors)`}`,
      );
    }
    lines.push('');
    return lines;
  }

  private renderChecklist(analysis: AnalysisResult): string[] {
    const manual = analysis.plans.flatMap((p) =>
      p.steps.filter((s) => s.kind === 'manual' || s.kind === 'official-codemod'),
    );
    const lines: string[] = [];
    lines.push('## Checklist');
    lines.push('');
    lines.push('- [ ] Review the plan above with your team');
    lines.push('- [ ] Run the migration on a dedicated branch (`upgrade-assistant migrate`)');
    for (const step of manual) {
      lines.push(`- [ ] ${step.title}${step.files.length ? ` (${step.files.length} files)` : ''}`);
    }
    lines.push('- [ ] Install dependencies and run your test suite');
    lines.push('- [ ] Smoke-test critical flows before merging');
    lines.push('');
    return lines;
  }

  private renderSources(analysis: AnalysisResult): string[] {
    const seen = new Map<string, string>();
    for (const plan of analysis.plans) {
      for (const finding of plan.findings) {
        for (const source of finding.rule.sources) {
          seen.set(source.url, source.title);
        }
      }
    }
    if (seen.size === 0) return [];
    const lines: string[] = [];
    lines.push('## Official links');
    lines.push('');
    for (const [url, title] of seen) lines.push(`- [${title}](${url})`);
    lines.push('');
    return lines;
  }
}

function countFindings(analysis: AnalysisResult): number {
  return analysis.plans.reduce(
    (sum, p) => sum + p.findings.reduce((s, f) => s + f.matches.length, 0),
    0,
  );
}

function countAffectedFiles(analysis: AnalysisResult): number {
  const files = new Set<string>();
  for (const plan of analysis.plans) {
    for (const finding of plan.findings) {
      for (const match of finding.matches) files.add(match.filePath);
    }
  }
  return files.size;
}

function riskBadge(plan: UpgradePlan): string {
  return { low: '🟢 low', medium: '🟡 medium', high: '🔴 high' }[plan.risk];
}

function severityIcon(finding: Finding): string {
  return { breaking: '🛑', warning: '⚠️', info: 'ℹ️' }[finding.rule.severity];
}

function fixLabel(finding: Finding): string {
  return {
    autofix: '✨ automatic (Upgrade Assistant)',
    'official-codemod': '🔧 official codemod',
    manual: '✋ manual',
  }[finding.rule.fix];
}

export function formatMinutes(minutes: number): string {
  if (minutes < 60) return `${Math.ceil(minutes)} min`;
  const hours = Math.floor(minutes / 60);
  const rest = Math.ceil(minutes % 60);
  return rest > 0 ? `${hours}h ${rest}min` : `${hours}h`;
}
